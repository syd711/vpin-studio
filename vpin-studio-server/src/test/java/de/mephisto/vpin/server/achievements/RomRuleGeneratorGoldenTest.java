package de.mephisto.vpin.server.achievements;

import tools.jackson.core.type.TypeReference;
import tools.jackson.databind.ObjectMapper;
import de.mephisto.vpin.server.achievements.nvram.MapField;
import de.mephisto.vpin.server.achievements.nvram.NvramAuditReader;
import de.mephisto.vpin.server.achievements.rules.AchievementRule;
import de.mephisto.vpin.server.achievements.rules.AchievementRuleSet;
import de.mephisto.vpin.server.achievements.rules.RomRuleGenerator;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

import java.io.File;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Compares the Java port with fixtures generated by the Python Achievement Watcher
 * (see src/test/resources/achievements/golden, generated from the real .nv files in resources/nvrams).
 */
public class RomRuleGeneratorGoldenTest {

  static final File GOLDEN = new File("src/test/resources/achievements/golden");
  /** Subset of resources/maps for the 20 golden ROMs, refresh with achievements/copy_test_maps.py after a map update. */
  static final File MAPS = new File("src/test/resources/achievements/maps");
  static final ObjectMapper MAPPER = new ObjectMapper();
  static NvramAuditReader reader;

  @BeforeAll
  static void setup() {
    reader = new NvramAuditReader(MAPS);
  }

  @ParameterizedTest
  @ValueSource(strings = {"afm_113b", "mm_109c", "tz_94h", "taf_l7", "cc_13", "tom_14h", "apollo13", "lw3_208", "baywatch",
      "twd_160", "godzilla", "mb_106b", "ss_15", "xenon", "centaur", "sttng_l7", "bop_l7", "rs_l6", "gladiatr", "bk2k_l4"})
  void fieldsMatchWatcher(String rom) throws Exception {
    List<Map<String, String>> expected = MAPPER.readValue(new File(GOLDEN, rom + ".fields.json"), new TypeReference<>() {
    });
    List<MapField> actual = reader.getFields(rom);
    assertThat(actual.stream().map(f -> f.label() + "|" + f.section()).toList())
        .containsExactlyElementsOf(expected.stream().map(m -> m.get("label") + "|" + m.get("section")).toList());
  }

  @ParameterizedTest
  @ValueSource(strings = {"afm_113b", "mm_109c", "tz_94h", "taf_l7", "cc_13", "tom_14h", "apollo13", "lw3_208", "baywatch",
      "twd_160", "godzilla", "mb_106b", "ss_15", "xenon", "centaur", "sttng_l7", "bop_l7", "rs_l6", "gladiatr", "bk2k_l4"})
  void rulesMatchWatcher(String rom) throws Exception {
    LinkedHashMap<String, Object> audits = MAPPER.readValue(new File(GOLDEN, rom + ".audits.json"), new TypeReference<>() {
    });
    AchievementRuleSet expected = AchievementRuleSet.load(new File(GOLDEN, rom + ".ach.json"));
    List<AchievementRule> actual = RomRuleGenerator.generate(rom, audits, reader.getFields(rom));
    assertThat(MAPPER.writeValueAsString(actual)).isEqualTo(MAPPER.writeValueAsString(expected.getRules()));
  }
}
